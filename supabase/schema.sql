create table if not exists public.lancamentos (
  id          bigint generated by default as identity primary key,
  ano         int  not null check (ano between 2000 and 2100),
  mes         int  not null check (mes between 1 and 12),
  tipo        text not null check (tipo in ('entrada', 'saida')),
  descricao   text not null,
  categoria   text not null,
  valor       numeric(12,2) not null check (valor >= 0),
  criado_por  uuid default auth.uid() references auth.users(id),
  criado_em   timestamptz not null default now()
);
create index if not exists lancamentos_ano_mes on public.lancamentos (ano, mes);

-- Importação de faturas (CSV do Nubank). Pode rodar de novo sem problema.
alter table public.lancamentos add column if not exists cartao      text;  -- 'Nubank' etc.; vazio = lançamento comum
alter table public.lancamentos add column if not exists data_compra date;
alter table public.lancamentos add column if not exists import_key  text;  -- evita importar a mesma compra duas vezes
create unique index if not exists lancamentos_import_key on public.lancamentos (import_key);
-- Estornos e créditos do cartão entram negativos para o total bater com a fatura.
alter table public.lancamentos drop constraint if exists lancamentos_valor_check;
alter table public.lancamentos add constraint lancamentos_valor_check check (valor >= 0 or cartao is not null);

create table if not exists public.investimentos (
  id              bigint generated by default as identity primary key,
  nome            text not null,
  tipo            text not null,
  instituicao     text,
  valor_aplicado  numeric(14,2) not null default 0,
  valor_atual     numeric(14,2) not null default 0,
  data_aplicacao  date,
  objetivo        text,
  criado_por      uuid default auth.uid() references auth.users(id),
  criado_em       timestamptz not null default now()
);

-- Segurança: só usuários logados acessam. Como o cadastro público fica
-- desligado, os únicos usuários são os que vocês criarem no painel.
alter table public.lancamentos   enable row level security;
alter table public.investimentos enable row level security;

drop policy if exists "casa_lancamentos" on public.lancamentos;
create policy "casa_lancamentos" on public.lancamentos
  for all to authenticated using (true) with check (true);

drop policy if exists "casa_investimentos" on public.investimentos;
create policy "casa_investimentos" on public.investimentos
  for all to authenticated using (true) with check (true);

-- ---------- Finanças: orçamento por categoria ----------
create table if not exists public.orcamentos (
  id         bigint generated by default as identity primary key,
  categoria  text not null unique,
  teto       numeric(12,2) not null check (teto > 0),
  criado_em  timestamptz not null default now()
);
alter table public.orcamentos enable row level security;
drop policy if exists "casa_orcamentos" on public.orcamentos;
create policy "casa_orcamentos" on public.orcamentos
  for all to authenticated using (true) with check (true);

-- ---------- Finanças: contas a pagar ----------
create table if not exists public.contas (
  id              bigint generated by default as identity primary key,
  descricao       text not null,
  categoria       text not null,
  valor_previsto  numeric(12,2) not null default 0 check (valor_previsto >= 0),
  dia_vencimento  int check (dia_vencimento between 1 and 31),
  recorrente      boolean not null default true,   -- todo mês; senão é avulsa e usa "vencimento"
  vencimento      date,
  ativa           boolean not null default true,
  criado_por      uuid default auth.uid() references auth.users(id),
  criado_em       timestamptz not null default now()
);
create table if not exists public.contas_pagamentos (
  id             bigint generated by default as identity primary key,
  conta_id       bigint not null references public.contas(id) on delete cascade,
  ano            int not null,
  mes            int not null check (mes between 1 and 12),
  pago_em        date not null default current_date,
  valor          numeric(12,2) not null check (valor >= 0),
  lancamento_id  bigint references public.lancamentos(id) on delete set null,
  criado_em      timestamptz not null default now(),
  unique (conta_id, ano, mes)
);
alter table public.contas enable row level security;
alter table public.contas_pagamentos enable row level security;
drop policy if exists "casa_contas" on public.contas;
create policy "casa_contas" on public.contas
  for all to authenticated using (true) with check (true);
drop policy if exists "casa_contas_pagamentos" on public.contas_pagamentos;
create policy "casa_contas_pagamentos" on public.contas_pagamentos
  for all to authenticated using (true) with check (true);

-- ---------- Lista de compras (app + skill da Alexa) ----------
create table if not exists public.compras_itens (
  id           bigint generated by default as identity primary key,
  nome         text not null,
  quantidade   text,
  comprado     boolean not null default false,
  comprado_em  timestamptz,
  origem       text not null default 'app' check (origem in ('app', 'alexa')),
  criado_por   uuid default auth.uid() references auth.users(id),
  criado_em    timestamptz not null default now()
);
create index if not exists compras_itens_comprado on public.compras_itens (comprado, criado_em);
alter table public.compras_itens enable row level security;
drop policy if exists "casa_compras" on public.compras_itens;
create policy "casa_compras" on public.compras_itens
  for all to authenticated using (true) with check (true);

-- Atualização em tempo real entre os celulares (e quando a Alexa adiciona um item).
do $$ begin
  alter publication supabase_realtime add table public.compras_itens;
exception when duplicate_object then null;
end $$;

-- ---------- Calendário (Google Agenda de cada pessoa, compartilhado com a casa) ----------
-- Tokens do Google: só as Edge Functions (chave de serviço) leem e gravam. Ficam cifrados.
create table if not exists public.cal_tokens (
  user_id                uuid primary key references auth.users(id) on delete cascade,
  refresh_token_cifrado  text not null,
  access_token_cifrado   text,
  expira_em              timestamptz,
  escopos                text,
  atualizado_em          timestamptz not null default now()
);
alter table public.cal_tokens enable row level security;  -- sem nenhuma policy: o app não enxerga
revoke all on public.cal_tokens from anon, authenticated;
grant all on public.cal_tokens to service_role;

-- Quem já conectou o Google (todos da casa veem; só a função grava).
create table if not exists public.cal_contas (
  user_id       uuid primary key references auth.users(id) on delete cascade,
  nome          text not null,
  google_email  text,
  conectado_em  timestamptz not null default now(),
  ultimo_sync   timestamptz,
  erro          text
);

-- Agendas de cada conta. Ninguém vê uma agenda até o dono marcar "compartilhada".
create table if not exists public.cal_agendas (
  id                  bigint generated by default as identity primary key,
  user_id             uuid not null references auth.users(id) on delete cascade,
  google_calendar_id  text not null,
  nome                text not null,
  cor_google          text,
  cor                 text,                                  -- cor escolhida no app (sobrepõe a do Google)
  principal           boolean not null default false,
  pode_escrever       boolean not null default false,        -- o dono pode criar eventos nela no Google
  compartilhada       boolean not null default false,
  familia_pode_criar  boolean not null default false,
  sync_token          text,
  unique (user_id, google_calendar_id)
);

create table if not exists public.cal_eventos (
  id                   bigint generated by default as identity primary key,
  agenda_id            bigint not null references public.cal_agendas(id) on delete cascade,
  google_event_id      text not null,
  titulo               text not null,
  descricao            text,
  local                text,
  inicio               timestamptz not null,
  fim                  timestamptz not null,
  dia_inteiro          boolean not null default false,  -- dia inteiro: início/fim à meia-noite de Brasília, fim exclusivo
  link_google          text,
  criado_pelo_app_por  uuid references auth.users(id) on delete set null,
  atualizado_em        timestamptz not null default now(),
  sincronizado_em      timestamptz not null default now(),
  unique (agenda_id, google_event_id)
);
create index if not exists cal_eventos_inicio on public.cal_eventos (inicio);

alter table public.cal_contas  enable row level security;
alter table public.cal_agendas enable row level security;
alter table public.cal_eventos enable row level security;
grant all on public.cal_contas, public.cal_agendas, public.cal_eventos to service_role;
revoke all on public.cal_contas, public.cal_agendas, public.cal_eventos from anon, authenticated;
grant select on public.cal_contas, public.cal_agendas, public.cal_eventos to authenticated;
-- o dono só pode mudar estas colunas da agenda; o resto vem do Google pela função
grant update (compartilhada, familia_pode_criar, cor) on public.cal_agendas to authenticated;

drop policy if exists "cal_contas_ver" on public.cal_contas;
create policy "cal_contas_ver" on public.cal_contas for select to authenticated using (true);

drop policy if exists "cal_agendas_ver" on public.cal_agendas;
create policy "cal_agendas_ver" on public.cal_agendas for select to authenticated
  using (compartilhada or user_id = auth.uid());
drop policy if exists "cal_agendas_dono" on public.cal_agendas;
create policy "cal_agendas_dono" on public.cal_agendas for update to authenticated
  using (user_id = auth.uid()) with check (user_id = auth.uid());

drop policy if exists "cal_eventos_ver" on public.cal_eventos;
create policy "cal_eventos_ver" on public.cal_eventos for select to authenticated
  using (exists (select 1 from public.cal_agendas a
                 where a.id = cal_eventos.agenda_id and (a.compartilhada or a.user_id = auth.uid())));

do $$ begin
  alter publication supabase_realtime add table public.cal_eventos;
exception when duplicate_object then null;
end $$;
do $$ begin
  alter publication supabase_realtime add table public.cal_agendas;
exception when duplicate_object then null;
end $$;

