-- ---------- Calendário (Google Agenda de cada pessoa, compartilhado com a casa) ----------
-- Tokens do Google: só as Edge Functions (chave de serviço) leem e gravam. Ficam cifrados.
create table if not exists public.cal_tokens (
  user_id                uuid primary key references auth.users(id) on delete cascade,
  refresh_token_cifrado  text not null,
  access_token_cifrado   text,
  expira_em              timestamptz,
  escopos                text,
  atualizado_em          timestamptz not null default now()
);
alter table public.cal_tokens enable row level security;  -- sem nenhuma policy: o app não enxerga
revoke all on public.cal_tokens from anon, authenticated;
grant all on public.cal_tokens to service_role;

-- Quem já conectou o Google (todos da casa veem; só a função grava).
create table if not exists public.cal_contas (
  user_id       uuid primary key references auth.users(id) on delete cascade,
  nome          text not null,
  google_email  text,
  conectado_em  timestamptz not null default now(),
  ultimo_sync   timestamptz,
  erro          text
);

-- Agendas de cada conta. Ninguém vê uma agenda até o dono marcar "compartilhada".
create table if not exists public.cal_agendas (
  id                  bigint generated by default as identity primary key,
  user_id             uuid not null references auth.users(id) on delete cascade,
  google_calendar_id  text not null,
  nome                text not null,
  cor_google          text,
  cor                 text,                                  -- cor escolhida no app (sobrepõe a do Google)
  principal           boolean not null default false,
  pode_escrever       boolean not null default false,        -- o dono pode criar eventos nela no Google
  compartilhada       boolean not null default false,
  familia_pode_criar  boolean not null default false,
  sync_token          text,
  unique (user_id, google_calendar_id)
);

create table if not exists public.cal_eventos (
  id                   bigint generated by default as identity primary key,
  agenda_id            bigint not null references public.cal_agendas(id) on delete cascade,
  google_event_id      text not null,
  titulo               text not null,
  descricao            text,
  local                text,
  inicio               timestamptz not null,
  fim                  timestamptz not null,
  dia_inteiro          boolean not null default false,  -- dia inteiro: início/fim à meia-noite de Brasília, fim exclusivo
  link_google          text,
  criado_pelo_app_por  uuid references auth.users(id) on delete set null,
  atualizado_em        timestamptz not null default now(),
  sincronizado_em      timestamptz not null default now(),
  unique (agenda_id, google_event_id)
);
create index if not exists cal_eventos_inicio on public.cal_eventos (inicio);

alter table public.cal_contas  enable row level security;
alter table public.cal_agendas enable row level security;
alter table public.cal_eventos enable row level security;
grant all on public.cal_contas, public.cal_agendas, public.cal_eventos to service_role;
revoke all on public.cal_contas, public.cal_agendas, public.cal_eventos from anon, authenticated;
grant select on public.cal_contas, public.cal_agendas, public.cal_eventos to authenticated;
-- o dono só pode mudar estas colunas da agenda; o resto vem do Google pela função
grant update (compartilhada, familia_pode_criar, cor) on public.cal_agendas to authenticated;

drop policy if exists "cal_contas_ver" on public.cal_contas;
create policy "cal_contas_ver" on public.cal_contas for select to authenticated using (true);

drop policy if exists "cal_agendas_ver" on public.cal_agendas;
create policy "cal_agendas_ver" on public.cal_agendas for select to authenticated
  using (compartilhada or user_id = auth.uid());
drop policy if exists "cal_agendas_dono" on public.cal_agendas;
create policy "cal_agendas_dono" on public.cal_agendas for update to authenticated
  using (user_id = auth.uid()) with check (user_id = auth.uid());

drop policy if exists "cal_eventos_ver" on public.cal_eventos;
create policy "cal_eventos_ver" on public.cal_eventos for select to authenticated
  using (exists (select 1 from public.cal_agendas a
                 where a.id = cal_eventos.agenda_id and (a.compartilhada or a.user_id = auth.uid())));

do $$ begin
  alter publication supabase_realtime add table public.cal_eventos;
exception when duplicate_object then null;
end $$;
do $$ begin
  alter publication supabase_realtime add table public.cal_agendas;
exception when duplicate_object then null;
end $$;

