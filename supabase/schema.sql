create table if not exists public.lancamentos (
  id          bigint generated by default as identity primary key,
  ano         int  not null check (ano between 2000 and 2100),
  mes         int  not null check (mes between 1 and 12),
  tipo        text not null check (tipo in ('entrada', 'saida')),
  descricao   text not null,
  categoria   text not null,
  valor       numeric(12,2) not null check (valor >= 0),
  criado_por  uuid default auth.uid() references auth.users(id),
  criado_em   timestamptz not null default now()
);
create index if not exists lancamentos_ano_mes on public.lancamentos (ano, mes);

-- Importação de faturas (CSV do Nubank). Pode rodar de novo sem problema.
alter table public.lancamentos add column if not exists cartao      text;  -- 'Nubank' etc.; vazio = lançamento comum
alter table public.lancamentos add column if not exists data_compra date;
alter table public.lancamentos add column if not exists import_key  text;  -- evita importar a mesma compra duas vezes
create unique index if not exists lancamentos_import_key on public.lancamentos (import_key);
-- Estornos e créditos do cartão entram negativos para o total bater com a fatura.
alter table public.lancamentos drop constraint if exists lancamentos_valor_check;
alter table public.lancamentos add constraint lancamentos_valor_check check (valor >= 0 or cartao is not null);

create table if not exists public.investimentos (
  id              bigint generated by default as identity primary key,
  nome            text not null,
  tipo            text not null,
  instituicao     text,
  valor_aplicado  numeric(14,2) not null default 0,
  valor_atual     numeric(14,2) not null default 0,
  data_aplicacao  date,
  objetivo        text,
  criado_por      uuid default auth.uid() references auth.users(id),
  criado_em       timestamptz not null default now()
);

-- Segurança: só usuários logados acessam. Como o cadastro público fica
-- desligado, os únicos usuários são os que vocês criarem no painel.
alter table public.lancamentos   enable row level security;
alter table public.investimentos enable row level security;

drop policy if exists "casa_lancamentos" on public.lancamentos;
create policy "casa_lancamentos" on public.lancamentos
  for all to authenticated using (true) with check (true);

drop policy if exists "casa_investimentos" on public.investimentos;
create policy "casa_investimentos" on public.investimentos
  for all to authenticated using (true) with check (true);

